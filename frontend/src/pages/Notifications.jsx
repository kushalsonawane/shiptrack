import { useEffect, useState } from "react";
import { Link } from "react-router-dom";

import { api, fmtDateTime } from "../api.js";
import { Badge, Button, Empty, ErrorNote, Loading, PageHead, Pager, StatusBadge } from "../components/ui.jsx";
import { IconBell } from "../components/Icons.jsx";

export default function Notifications() {
  const [status, setStatus] = useState("");
  const [channel, setChannel] = useState("");
  const [rawQ, setRawQ] = useState("");
  const [q, setQ] = useState("");
  const [page, setPage] = useState(1);
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);

  useEffect(() => {
    const timer = setTimeout(() => {
      setQ(rawQ);
      setPage(1);
    }, 300);
    return () => clearTimeout(timer);
  }, [rawQ]);

  const load = () => {
    const params = new URLSearchParams({ page: String(page), page_size: "20" });
    if (status) params.set("status", status);
    if (channel) params.set("channel", channel);
    if (q.trim()) params.set("q", q.trim());
    setData(null);
    setError(null);
    api(`/notifications?${params}`)
      .then(setData)
      .catch(setError);
  };

  useEffect(load, [status, channel, q, page]);

  const retry = async (notification) => {
    try {
      await api(`/notifications/${notification.id}/retry`, { method: "POST" });
      load();
    } catch (err) {
      setError(err);
    }
  };

  return (
    <div className="page">
      <PageHead
        title="Notification log"
        sub="Every dispatch, delivery and alert message generated by the communication engine"
      />
      <div className="toolbar">
        <select
          className="select"
          value={channel}
          onChange={(event) => {
            setChannel(event.target.value);
            setPage(1);
          }}
        >
          <option value="">Any channel</option>
          <option value="Email">Email</option>
          <option value="WhatsApp">WhatsApp</option>
          <option value="SMS">SMS</option>
        </select>
        <select
          className="select"
          value={status}
          onChange={(event) => {
            setStatus(event.target.value);
            setPage(1);
          }}
        >
          <option value="">Any status</option>
          <option value="Sent">Sent</option>
          <option value="Queued">Queued (no provider)</option>
          <option value="Failed">Failed</option>
          <option value="Pending">Pending</option>
        </select>
        <input
          className="input"
          placeholder="Recipient or subject"
          value={rawQ}
          onChange={(event) => setRawQ(event.target.value)}
        />
      </div>
      <ErrorNote error={error} />
      {!data ? (
        <Loading />
      ) : (
        <div className="card an">
          <div className="table-wrap">
            <table className="table">
              <thead>
                <tr>
                  <th>Sent at</th>
                  <th>Shipment</th>
                  <th>Channel</th>
                  <th>Recipient</th>
                  <th>Subject</th>
                  <th>Status</th>
                  <th></th>
                </tr>
              </thead>
              <tbody>
                {data.items.map((notification) => (
                  <tr key={notification.id}>
                    <td className="small">{fmtDateTime(notification.sent_at || notification.created_at)}</td>
                    <td className="mono small">
                      {notification.shipment_id ? (
                        <Link to={`/shipments/${notification.shipment_id}`}>{notification.shipment_no || notification.shipment_id}</Link>
                      ) : (
                        "–"
                      )}
                    </td>
                    <td>
                      <Badge tone={notification.channel === "Email" ? "blue" : "green"}>
                        {notification.channel}
                      </Badge>
                    </td>
                    <td className="small mono">{notification.recipient}</td>
                    <td className="small">{notification.subject}</td>
                    <td>
                      <StatusBadge status={notification.status} />
                      {notification.retry_count ? (
                        <span className="small muted"> x{notification.retry_count}</span>
                      ) : null}
                    </td>
                    <td>
                      {notification.status === "Failed" && (
                        <Button variant="ghost" size="sm" onClick={() => retry(notification)}>
                          Retry
                        </Button>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          {data.items.length === 0 && (
            <Empty
              icon={IconBell}
              title="No notifications found"
              hint="Dispatch a shipment or run the alert rules to generate communication."
            />
          )}
          <Pager page={data.page} pageSize={data.page_size} total={data.total} onPage={setPage} />
        </div>
      )}
    </div>
  );
}
